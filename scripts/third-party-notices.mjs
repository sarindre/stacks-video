// Writes THIRD_PARTY_NOTICES.md: every package that ships inside the app (production dependencies and
// everything they pull in), with its license, so the project can credit and comply with them.
//
//   npm run licenses
//
// It also prints a warning for any license that needs a second look (copyleft or unknown).

import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";

const raw = execSync("npm ls --omit=dev --all --json", { maxBuffer: 64 * 1024 * 1024, stdio: ["ignore", "pipe", "ignore"] }).toString();
const tree = JSON.parse(raw);

const found = new Map();
(function walk(deps) {
  for (const [name, info] of Object.entries(deps || {})) {
    const key = `${name}@${info.version}`;
    if (!found.has(key)) found.set(key, { name, version: info.version });
    walk(info.dependencies);
  }
})(tree.dependencies);

const read = (name) => {
  try {
    return JSON.parse(fs.readFileSync(path.join("node_modules", name, "package.json"), "utf8"));
  } catch {
    return null;
  }
};
const licenseOf = (pkg) => {
  const l = pkg?.license ?? pkg?.licenses;
  if (!l) return "UNKNOWN";
  if (typeof l === "string") return l;
  if (Array.isArray(l)) return l.map((x) => x.type || x).join(" OR ");
  return l.type || "UNKNOWN";
};

const rows = [...found.values()]
  .map(({ name, version }) => {
    const pkg = read(name);
    return { name, version, license: licenseOf(pkg), homepage: (typeof pkg?.homepage === "string" && pkg.homepage) || pkg?.repository?.url?.replace(/^git\+/, "").replace(/\.git$/, "") || "" };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const needsLook = rows.filter((r) => /GPL|AGPL|LGPL|SSPL|UNKNOWN|UNLICENSED|CC-BY-NC/i.test(r.license));
const byLicense = rows.reduce((m, r) => m.set(r.license, (m.get(r.license) || 0) + 1), new Map());

const md = `# Third-party notices

Stacks Video's own code is covered by the project's license. The packages below ship inside the app, and each is used under its own license. Generated by \`npm run licenses\` (production dependencies only; build tools are not shipped).

## Data, images and fonts

Stacks Video ships no data or artwork from these services. It contacts them from your own device, with your own key where one is needed, only when you use a feature that needs them:

- **Movie and TV data and images** come from [TMDB](https://www.themoviedb.org/). This product uses TMDB and the TMDB APIs but is not endorsed, certified, or otherwise approved by TMDB. The TMDB logo is TMDB's own file, unmodified.
- **Game data** comes from [RAWG](https://rawg.io/).
- **Book data and covers** come from [Open Library](https://openlibrary.org/).
- **Music data** comes from [MusicBrainz](https://musicbrainz.org/) (core data is CC0) and cover art from the [Cover Art Archive](https://coverartarchive.org/).
- **Disc barcode lookups** use the free tier of [UPCitemdb](https://www.upcitemdb.com/).
- **Bungee** (by David Jonathan Ross) and **Barlow Condensed** (by Jeremy Tribby) are bundled under the [SIL Open Font License 1.1](https://openfontlicense.org/).
- **Icons** are from [Lucide](https://lucide.dev/) (ISC license).
- **Desktop app:** Electron and Chromium (their license files are shipped with the desktop app as \`LICENSE.electron.txt\` and \`LICENSES.chromium.html\`).

## Packages shipped in the app (${rows.length})

Licenses in use: ${[...byLicense.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(", ")}.

| Package | Version | License |
| --- | --- | --- |
${rows.map((r) => `| ${r.homepage ? `[${r.name}](${r.homepage})` : r.name} | ${r.version} | ${r.license} |`).join("\n")}
`;
fs.writeFileSync("THIRD_PARTY_NOTICES.md", md);

console.log(`Wrote THIRD_PARTY_NOTICES.md (${rows.length} packages).`);
if (needsLook.length) {
  console.log("\nLook at these licenses before releasing:");
  for (const r of needsLook) console.log(`  ${r.name}@${r.version}: ${r.license}`);
} else {
  console.log("No copyleft or unknown licenses found.");
}
